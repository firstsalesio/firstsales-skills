// Rewrites the command table in each reference file from `firstsales commands --json`.
// Only the text between the markers changes; the notes around it are hand-written.
// Usage: node scripts/gen-reference.mjs   (FIRSTSALES_CLI overrides the binary)
import { execSync } from 'node:child_process';
import { readFileSync, writeFileSync, existsSync } from 'node:fs';

const AREAS = {
  'campaigns.md': ['campaigns', 'testimonials', 'blocked-domains', 'sequences'],
  'contacts-lists-companies.md': ['contacts', 'contact-lists', 'contact-tags', 'contact-imports', 'contact-exports', 'contact-fields', 'companies', 'suppression'],
  'inbox-templates.md': ['inbox'],
  'emails-compose.md': ['emails'],
  'signals.md': ['signals'],
  'senders-domains-deliverability.md': ['connectors', 'tracking-domains', 'warmup', 'email-auth'],
  'crm-deals-activities.md': ['deals', 'pipelines', 'activities'],
  'billing-usage.md': ['billing', 'usage'],
  'team-access-keys.md': ['whoami', 'doctor', 'orgs', 'organizations', 'workspaces', 'members', 'teams', 'invitations', 'groups', 'domains', 'api-keys'],
  'knowledge-offerings.md': ['kb', 'offerings'],
  'copilot-learning-alerts.md': ['copilot', 'learning', 'alerts'],
  'changelog-dashboard.md': ['changelog', 'dashboard'],
};
const START = '<!-- commands:start (generated by scripts/gen-reference.mjs) -->';
const END = '<!-- commands:end -->';
const DIR = 'skills/firstsales/references';

const cli = process.env.FIRSTSALES_CLI ?? 'npx -y @firstsales.io/cli@latest';
const { commands } = JSON.parse(execSync(`${cli} commands --json`, { encoding: 'utf8' }));

const areaOf = Object.fromEntries(Object.entries(AREAS).flatMap(([f, ps]) => ps.map((p) => [p, f])));
const unknown = [...new Set(commands.map((c) => c.command.split(' ')[0]))].filter((p) => !areaOf[p]);
if (unknown.length) {
  console.error(`New CLI areas need a home in AREAS: ${unknown.join(', ')}`);
  process.exit(1);
}

const short = (p) => p.replace('/api/v1/organizations/{org}/workspaces/{workspace}', '…/{workspace}').replace('/api/v1/organizations/{org}', '…/{org}');
const needs = (c) => c.required.filter((r) => r !== 'org' && r !== 'workspace').map((r) => `\`--${r}\``).join(' ') || '-';

for (const [file, prefixes] of Object.entries(AREAS)) {
  const rows = commands
    .filter((c) => prefixes.includes(c.command.split(' ')[0]))
    .map((c) => `| \`firstsales ${c.command}\` | ${c.method} | \`${short(c.path)}\` | ${needs(c)} | ${c.destructive ? 'yes, needs `--confirm`' : 'no'} |`);
  const table = [START, '', '| Command | Method | Path | Needs | Destructive |', '| --- | --- | --- | --- | --- |', ...rows, '', END].join('\n');
  const path = `${DIR}/${file}`;
  const text = existsSync(path) ? readFileSync(path, 'utf8') : `# ${file}\n\n${START}\n${END}\n`;
  if (!text.includes(START)) throw new Error(`${path} has no command markers`);
  writeFileSync(path, text.replace(new RegExp(`${START.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${END}`), table));
}
console.log(`${commands.length} commands written to ${Object.keys(AREAS).length} files`);
